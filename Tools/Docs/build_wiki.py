#!/usr/bin/env python3
"""Render the repository wiki from AGENTS.md using only the Python standard library."""

import argparse
import difflib
import json
import re
from pathlib import Path

from wiki_reader import load_player_guide, player_markdown, render_reader


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "Docs" / "Wiki"
# Prefixes allow dated headings to change without changing the navigation.
PAGES = (
    ("journey.md", "Journey & game design", ("Gameplan",)),
    ("architecture.md", "Architecture & systems", ("Stack", "Layout", "Architecture")),
    ("development.md", "Development workflow", (
        "Conventions / gotchas", "Issue workflow", "Agent workflow", "Cross-platform")),
    ("art-and-assets.md", "Art & asset pipeline", ("Art & assets", "Blender")),
    ("testing.md", "Testing playbook", ("Testing playbook",)),
    ("status.md", "Status & priorities", ("Status", "Next priorities")),
    ("maintenance.md", "Wiki maintenance", ("Living wiki",)),
)


def render():
    guide = load_player_guide(ROOT)
    source = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    parts = re.split(r"^## (.+)\n", source, flags=re.MULTILINE)
    sections = list(zip(parts[1::2], parts[2::2]))
    assigned = set()
    outputs = {}
    navigation = " | ".join(f"[{title}]({name})" for name, title, _ in PAGES)
    for name, title, prefixes in PAGES:
        selected = []
        for index, (heading, body) in enumerate(sections):
            if any(heading.startswith(prefix) for prefix in prefixes):
                if index in assigned:
                    raise ValueError(f"Section assigned twice: {heading}")
                assigned.add(index)
                selected.append(f"## {heading}\n\n{body.strip()}\n")
        if not selected:
            raise ValueError(f"No sections found for {name}")
        content = "\n".join(selected)
        # Markdown links from the root source need to resolve from Docs/Wiki.
        # Inline-code paths remain repository-relative, as stated on the index.
        content = re.sub(
            r"(\]\()([^\s)]+)(\))",
            lambda m: m[0] if re.match(r"(?:[a-zA-Z][\w+.-]*:|#|/)", m[2])
            else f"{m[1]}../../{m[2]}{m[3]}",
            content,
        )
        outputs[name] = (
            "<!-- Generated by Tools/Docs/build_wiki.py from AGENTS.md. Do not edit. -->\n\n"
            f"# {title}\n\n[Wiki home](README.md) | [Edit source](../../AGENTS.md)\n\n"
            + content + f"\n---\n\n{navigation}\n"
        )
    missing = [heading for i, (heading, _) in enumerate(sections) if i not in assigned]
    if missing:
        raise ValueError("Unmapped AGENTS.md sections: " + ", ".join(missing))
    rows = "\n".join(f"| [{title}]({name}) | {description} |" for (name, title, _), description in zip(PAGES, (
        "The journey home, terminology and intended gameplay.",
        "Unity stack, module layout, networking, ships, warp and planets.",
        "Coding conventions, issues, Unity tools and Mac/Windows setup.",
        "Asset selection, import rules and reproducible Blender scripts.",
        "Cheap targeted checks, development scenarios and multiplayer verification.",
        "Recorded implementation status, limitations and the roadmap reference.",
        "How Claude and other agents keep this wiki current.",
    )))
    outputs["README.md"] = (
        "<!-- Generated by Tools/Docs/build_wiki.py from AGENTS.md. Do not edit. -->\n\n"
        "# Voidward Wiki — Spielen & Entwickeln\n\n"
        "**[Open the visual wiki](index.html)** — browser navigation, full-text search, "
        "illustrated introductions and expandable technical references. Open `Docs/Wiki/index.html` "
        "locally in your browser; no server or installation is required.\n\n"
        "Co-op space roguelite for 1–4 players: the SELENE-4 crew's journey home.\n\n"
        "## Spielerhandbuch\n\n"
        + '\n'.join(f'- [{page["title"]}]({page["id"]}.md): {page["summary"]}' for page in guide['pages'])
        + "\n\n## Entwicklerbereich\n\n| Page | Contents |\n| --- | --- |\n" + rows + "\n\n"
        "Start with Development workflow and the relevant system page before changing code. "
        "For running the game and controls, see the [player README](../../README.md). "
        "The detailed design and glossary live in [DESIGN.md](../../Assets/Design/DESIGN.md); "
        "asset attribution lives in [CREDITS.md](../../Assets/_Project/Art/CREDITS.md).\n\n"
        "The technical wiki is generated from [AGENTS.md](../../AGENTS.md); the player handbook "
        "from [player_guide.json](../../Tools/Docs/player_guide.json). Inline-code file paths are "
        "relative to the repository root. Dated source headings describe recorded knowledge, "
        "not a new test run. Planned features are not implementation claims.\n\n"
        "Claude enters through [CLAUDE.md](../../CLAUDE.md) and updates the source alongside "
        "relevant code changes. Run `python3 Tools/Docs/build_wiki.py` from the repository root "
        "to rebuild; `python3 Tools/Docs/build_wiki.py --check` detects stale or missing pages. "
        "CI runs the same check. No AI credentials or hosted wiki service are required.\n"
    )
    # Keep the Markdown view illustrated too, using the same editorial source.
    editorial = json.loads((ROOT / 'Tools/Docs/wiki_content.json').read_text(encoding='utf-8'))
    for name, _, _ in PAGES:
        images = editorial.get(name[:-3], {}).get('images', [])
        if images:
            gallery = '\n## Visual examples\n\n' + '\n\n'.join(
                f'![{item["alt"]}](../../{item["path"]})\n\n{item["caption"]}' for item in images
            ) + '\n'
            outputs[name] = outputs[name].replace('\n---\n', gallery + '\n---\n')
    outputs.update(player_markdown(guide))
    outputs['index.html'] = render_reader(ROOT, outputs, PAGES)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale or missing pages without writing")
    args = parser.parse_args()
    try:
        outputs = render()
    except ValueError as error:
        parser.exit(1, f"Wiki generation failed: {error}\n")
    # Removed chapters must not survive as apparently current documentation.
    obsolete = []
    for path in OUTPUT.glob('*'):
        if path.name in outputs or path.suffix not in ('.md', '.html'):
            continue
        if path.read_text(encoding='utf-8').startswith('<!-- Generated'):
            obsolete.append(path)
    if args.check and obsolete:
        parser.exit(1, 'Obsolete generated wiki pages: ' + ', '.join(path.name for path in obsolete)
                    + '\nRun: python3 Tools/Docs/build_wiki.py\n')
    stale = []
    for name, expected in outputs.items():
        path = OUTPUT / name
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual == expected:
            continue
        stale.append(name)
        if args.check:
            print("".join(difflib.unified_diff(
                actual.splitlines(keepends=True), expected.splitlines(keepends=True),
                fromfile=f"Docs/Wiki/{name}", tofile=f"generated/{name}",
            )), end="")
        else:
            OUTPUT.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as target:
                target.write(expected)
    if args.check and stale:
        parser.exit(1, "Wiki is stale. Run: python3 Tools/Docs/build_wiki.py\n")
    for path in obsolete:
        path.unlink()
    print(f"Wiki {'verified' if args.check else 'generated'}: {len(outputs)} pages.")


if __name__ == "__main__":
    main()
